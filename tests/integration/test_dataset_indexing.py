def test_minimal_index_creation_for_download_failure(get_and_clear_up_context):  # noqa: F811
    context = get_and_clear_up_context

    context["DATA_REGISTRY_BASE_URL"] = "http://localhost:3000/ckan-registration/datasets-03-1-dataset-404"
    datasets_in_bds = {}
    checker_run(context, datasets_in_bds)

    minimal_index = download_index_from_azure(context, get_dataset_index_name(context, "minimal"))

    dataset = datasets_in_bds[uuid.UUID("c8a40aa5-9f31-4bcf-a36f-51c1fc2cc159")]

    dataset_index_item = find_object_by_key(minimal_index["datasets"], "short_name", dataset["short_name"])

    assert dataset_index_item is not None

    for field in get_minimal_index_dataset_fields(context):
        if isinstance(dataset[field], uuid.UUID):
            assert uuid.UUID(dataset_index_item[field]) == dataset[field]
        elif dataset[field] is None or isinstance(dataset[field], str):
            assert dataset_index_item[field] == dataset[field]

    assert dataset_index_item["url_xml"] is None
    assert dataset_index_item["url_zip"] is None

    # -2 because of the two autogenerated fields
    assert len(dataset_index_item.keys()) - 2 == len(get_minimal_index_dataset_fields(context))


def full_index_common_checks(context: dict, dataset: dict, index_item: dict | None):

    assert index_item is not None

    for field in get_full_index_dataset_source_fields(context):
        if field == "download_error_message" or field == "head_error_message":
            continue
        if isinstance(dataset[field], uuid.UUID):
            assert uuid.UUID(index_item[field]) == dataset[field]
        elif dataset[field] is None or isinstance(dataset[field], str):
            assert index_item[field] == dataset[field]


